"""Generate pipeline/manifests/instagram_10_conversion_ideas.json from the idea modules.

Usage:  python pipeline/tools/ig10/build_manifest.py [--check]
--check exits 1 if the committed JSON is stale (for CI / Stage-2 tests).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ig10.catalog import ROOT, COUPON, load_catalog  # noqa: E402
from ig10.common import PAY_FA, cta_fa, products, product_url  # noqa: E402
from ig10.ideas_01_05 import IDEAS as A  # noqa: E402
from ig10.ideas_06_10 import IDEAS as B  # noqa: E402

OUT = ROOT / "pipeline" / "manifests" / "instagram_10_conversion_ideas.json"


def subtitle_cues(duration: float, pills: list[str]) -> list[dict]:
    """Spread the RTL pills evenly across the shot (0.25 s head/tail padding)."""
    span = (duration - 0.5) / len(pills)
    return [{"start": round(0.25 + k * span, 2), "end": round(0.25 + (k + 1) * span - 0.1, 2),
             "text": p, "direction": "rtl"} for k, p in enumerate(pills)]


def build() -> dict:
    cat = load_catalog()
    ideas = []
    for idea in A + B:
        shots = []
        for n, (d, vis, mot, fa, pills) in enumerate(idea["shots"], 1):
            shots.append({"shot_id": f"{idea['idea_id']}_S{n:02d}", "duration_sec": d,
                          "visual_prompt_flow": vis, "motion_prompt_flow": mot,
                          "spoken_fa": fa, "subtitles_rtl": ([{"start": 0, "end": 3, "text": idea["hook_fa"], "direction": "rtl"}] if n == 1 else subtitle_cues(d, pills))})
        ideas.append({
            "idea_id": idea["idea_id"], "title_fa": idea["title_fa"], "target_segment": idea["segment"],
            "persona_fa": idea["persona_fa"], "pain_point_fa": idea["pain_fa"],
            "psychological_trigger": idea["trigger"],
            "hook_duration_sec": 3, "hook_timing_status": "script_budget_not_audio_verified",
            "hook_3s_visual": idea["hook_visual"], "hook_3s_spoken_fa": idea["hook_fa"],
            "before_after_demo": {"before_fa": idea["before_fa"], "after_fa": idea["after_fa"]},
            "featured_products": [{"id": p["id"], "title": p["title"], "min_price_toman": p["min_price_toman"],
                                   "verified_in_seed": p["verified_in_seed"],
                                   "product_url": product_url(p["id"]), "url_status": "candidate_unverified_route",
                                   "role": "primary" if p["id"] == idea["primary_product_id"] else "optional_or_alternative"} for p in products(idea, cat)],
            "primary_product_id": idea["primary_product_id"],
            "price_anchor_toman": cat[idea["primary_product_id"]]["min_price_toman"],
            "comment_keyword": idea["keyword"], "cta_fa": cta_fa(idea, cat),
            "total_duration_sec": sum(s["duration_sec"] for s in shots), "shots": shots,
        })
    return {
        "_comment": "KelidBox @kelidbox_com — 10 Instagram conversion reels (Stage 1, Claude Opus 5.5). "
                    "Generated by pipeline/tools/ig10/build_manifest.py — edit the idea modules, not this file.",
        "schema_version": 2,
        "verification": {"scope": "offline_seed_and_user_brief", "checked_on": "2026-10-26",
                         "live_checkout_checked": False, "product_urls_verified": False,
                         "publish_gate": "Confirm real product permalinks and selected-plan eligibility before enabling DMs; review rendered speech/subtitles."},
        "render_contract": {"type": "idea_shot_planning_manifest", "direct_build_compatible": False,
                            "next_step": "Generate clips, retime subtitles and adapt to clip-level farsi_flow_workflow schema."}, "brand": "kelidbox.com", "instagram": "@kelidbox_com",
        "catalog_source": "docs/instagram-10-ideas/00-kelidbox-instagram-and-catalog-context.md",
        "coupon": COUPON,
        "installments": {"count": 4, "providers": ["TorobPay", "DigiPay"], "providers_fa": PAY_FA,
                         "source": "User-confirmed Stage-2 brief, 2026-10-26",
                         "eligibility_required": True, "coupon_stacking_verified": False,
                         "note": "Follow checkout terms; no claim of zero interest, universal approval or instant delivery."},
        "video": {"width": 720, "height": 1280, "fps": 24, "aspect": "9:16"},
        "subtitle_style": {"font": "Vazirmatn-Bold.ttf", "direction": "rtl", "style": "pill"},
        "ideas": ideas,
    }


def dumps(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


if __name__ == "__main__":
    text = dumps(build())
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("manifest up to date" if ok else "manifest STALE — rerun build_manifest.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text, encoding="utf-8")
    d = json.loads(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(d['ideas'])} ideas, "
          f"{sum(len(i['shots']) for i in d['ideas'])} shots")
